// Regenerates src/shared/dungeons.ts from Scryfall's oracle data for the dungeon cards.
// Usage: node scripts/generate-dungeons.mjs [saved-search.json]
import { readFile, writeFile } from 'node:fs/promises';

// Baldur's Gate Wilderness is a promotional card without printed paths, so it is left out.
const wanted = ['Lost Mine of Phandelver', 'Dungeon of the Mad Mage', 'Tomb of Annihilation', 'Undercity'];
const source = process.argv[2];
let cards;
if (source) cards = JSON.parse(await readFile(source, 'utf8')).data;
else {
  const url = `https://api.scryfall.com/cards/search?${new URLSearchParams({ q: 't:dungeon include:extras', unique: 'cards' })}`;
  const response = await fetch(url, {
    headers: {
      Accept: 'application/json',
      'User-Agent': 'CommandTable (+https://github.com/Addison16/command-table)',
    },
  });
  if (!response.ok) throw new Error(`Scryfall answered ${response.status}`);
  cards = (await response.json()).data;
}
const slug = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const dungeons = wanted.map((name) => {
  const card = cards.find((entry) => entry.name === name || entry.card_faces?.[0]?.name === name);
  if (!card) throw new Error(`Scryfall returned no ${name}`);
  const text = card.oracle_text ?? card.card_faces[0].oracle_text;
  // The Undercity opens with a reminder line that is not a room.
  const rooms = text
    .split('\n')
    .filter((line) => line.includes(' — '))
    .map((line) => {
      const match = /^(.+?) — (.+?)(?: \(Leads to: (.+)\))?$/.exec(line);
      if (!match) throw new Error(`Unreadable room in ${name}: ${line}`);
      return { name: match[1], text: match[2], leads: match[3]?.split(', ') ?? [] };
    });
  const index = new Map(rooms.map((room, i) => [room.name, i]));
  return {
    id: slug(name),
    name,
    scryfallId: card.id,
    rooms: rooms.map((room) => ({
      name: room.name,
      text: room.text,
      next: room.leads.map((lead) => {
        if (!index.has(lead)) throw new Error(`${name}: ${room.name} leads to unknown ${lead}`);
        return index.get(lead);
      }),
    })),
  };
});
for (const dungeon of dungeons) {
  const ends = dungeon.rooms.filter((room) => !room.next.length);
  if (ends.length !== 1 || ends[0] !== dungeon.rooms.at(-1))
    throw new Error(`${dungeon.name} has no single final room`);
}
const q = (value) => JSON.stringify(value);
await writeFile(
  'src/shared/dungeons.ts',
  `// Generated by scripts/generate-dungeons.mjs from Scryfall's oracle data for the dungeon cards.
// Card names and rules text are Wizards of the Coast's; see docs/assets.md. Regenerate rather than hand-edit.
export const dungeonIds = [${dungeons.map((d) => q(d.id)).join(', ')}] as const;
export type DungeonId = (typeof dungeonIds)[number];
/** \`next\` lists the rooms a room leads to, by position. The last room has none: it completes the dungeon. */
export type Dungeon = {
  id: DungeonId;
  name: string;
  scryfallId: string;
  rooms: readonly { name: string; text: string; next: readonly number[] }[];
};
export const dungeons: readonly Dungeon[] = [
${dungeons
  .map(
    (d) =>
      `  {\n    id: ${q(d.id)},\n    name: ${q(d.name)},\n    scryfallId: ${q(d.scryfallId)},\n    rooms: [\n${d.rooms
        .map((r) => `      { name: ${q(r.name)}, text: ${q(r.text)}, next: [${r.next.join(', ')}] },`)
        .join('\n')}\n    ],\n  },`,
  )
  .join('\n')}
];
export const dungeon = (id: string | undefined) => dungeons.find((entry) => entry.id === id);
`,
);
