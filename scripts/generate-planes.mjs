// Regenerates src/shared/planeIndex.ts and src/shared/planeCards.ts from Scryfall's oracle data.
// Usage: node scripts/generate-planes.mjs [saved-search.json]
// Without a file it queries Scryfall once for every plane and phenomenon card.
import { readFile, writeFile } from 'node:fs/promises';

const query = '(t:plane or t:phenomenon) -is:funny';
const source = process.argv[2];
let cards = [];
if (source) cards = JSON.parse(await readFile(source, 'utf8')).data;
else {
  let url = `https://api.scryfall.com/cards/search?${new URLSearchParams({ q: query, unique: 'cards', order: 'name' })}`;
  while (url) {
    const response = await fetch(url, {
      headers: {
        Accept: 'application/json',
        'User-Agent': 'CommandTable (+https://github.com/Addison16/command-table)',
      },
    });
    if (!response.ok) throw new Error(`Scryfall answered ${response.status}`);
    const page = await response.json();
    cards.push(...page.data);
    url = page.has_more ? page.next_page : '';
    if (url) await new Promise((resolve) => setTimeout(resolve, 200));
  }
}
// Secret Lair's showcase planes are reprints of the classic Planechase cards.
const sets = { opca: 'pca', moc: 'moc', who: 'who', pssc: 'pca' };
const slug = (name) =>
  name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const seen = new Set();
const planes = cards
  .map((card) => {
    const set = sets[card.set];
    if (!set) throw new Error(`Unknown planar set ${card.set} for ${card.name}`);
    const id = slug(card.name);
    if (seen.has(id)) throw new Error(`Duplicate plane id ${id}`);
    seen.add(id);
    return {
      id,
      name: card.name,
      set,
      phenomenon: /Phenomenon/.test(card.type_line),
      typeLine: card.type_line,
      scryfallId: card.id,
      text: card.oracle_text.replaceAll('{CHAOS}', 'chaos'),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));
const q = (value) => JSON.stringify(value);
const header =
  "// Generated by scripts/generate-planes.mjs from Scryfall's oracle data for every plane and phenomenon\n" +
  "// card. Card names and rules text are Wizards of the Coast's; see docs/assets.md. Regenerate rather than hand-edit.\n";
await writeFile(
  'src/shared/planeIndex.ts',
  `${header}export type PlaneSet = 'pca' | 'moc' | 'who';\n/** [id, name, set, phenomenon]. The rules text lives in planeCards.ts, loaded only when it is read. */\nexport const planeIndex: readonly (readonly [string, string, PlaneSet, boolean])[] = [\n${planes
    .map((p) => `  [${q(p.id)}, ${q(p.name)}, ${q(p.set)}, ${p.phenomenon}],`)
    .join('\n')}\n];\n`,
);
await writeFile(
  'src/shared/planeCards.ts',
  `${header}export type PlaneCard = { typeLine: string; scryfallId: string; text: string };\nexport const planeCards: Readonly<Record<string, PlaneCard>> = {\n${planes
    .map(
      (p) =>
        `  ${q(p.id)}: {\n    typeLine: ${q(p.typeLine)},\n    scryfallId: ${q(p.scryfallId)},\n    text: ${q(p.text)},\n  },`,
    )
    .join('\n')}\n};\n`,
);
console.log(`Wrote ${planes.length} planar cards.`);
